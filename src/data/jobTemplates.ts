// Fonction pour générer une description personnalisée COMPLÈTE
export const generateJobDescription = (
  templateId: number,
  data: {
    title: string;
    company: string;
    experience: string;
    skills: string[];
    city: string;
    country?: string;
    education?: string[];
    minYearsExperience?: number;
    languageRequirement?: string;
    gender?: string;
    maritalStatus?: string;
    minAge?: number;
    maxAge?: number;
    childrenAccepted?: boolean;
    drivingLicense?: string;
    contractType?: string;
    salaryMin?: number;
    salaryMax?: number;
    currency?: string;
    remote?: boolean;
    contactEmail?: string;
    contactPhone?: string;
    contactWhatsApp?: string;
    contactAddress?: string;
    contactWebsite?: string;
  }
): string => {
  const template = jobDescriptionTemplates.find(t => t.id === templateId);
  if (!template) return '';

  let description = template.template;
  
  // Remplacer les placeholders du template
  description = description.replace(/{title}/g, data.title);
  description = description.replace(/{company}/g, data.company);
  description = description.replace(/{experience}/g, data.experience);
  description = description.replace(/{city}/g, data.city);
  description = description.replace(/{skills}/g, data.skills.join(', '));

  // Ajouter les sections complètes
  description += '\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
  description += '\n📋 PROFIL RECHERCHÉ\n';
  description += '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n';

  // Compétences requises
  description += '✅ COMPÉTENCES REQUISES :\n';
  data.skills.forEach(skill => {
    description += `   • ${skill}\n`;
  });

  // Expérience
  description += `\n💼 EXPÉRIENCE :\n`;
  description += `   • Niveau : ${data.experience}\n`;
  if (data.minYearsExperience) {
    description += `   • Minimum ${data.minYearsExperience} an${data.minYearsExperience > 1 ? 's' : ''} d'expérience\n`;
  }

  // Diplôme
  if (data.education && data.education.length > 0) {
    description += `\n🎓 DIPLÔME REQUIS :\n`;
    const educationLabels: { [key: string]: string } = {
      'high_school': 'Baccalauréat',
      'bachelor': 'Licence / Bachelor',
      'master': 'Master / Maîtrise',
      'phd': 'Doctorat / PhD'
    };
    data.education.forEach(edu => {
      description += `   • ${educationLabels[edu] || edu}\n`;
    });
  }

  // Langue
  if (data.languageRequirement && data.languageRequirement !== 'none') {
    description += `\n🗣️ EXIGENCES LINGUISTIQUES :\n`;
    if (data.languageRequirement === 'bilingual') {
      description += `   • Bilingue Français ET Anglais (obligatoire)\n`;
    } else if (data.languageRequirement === 'french') {
      description += `   • Maîtrise du Français (obligatoire)\n`;
    } else if (data.languageRequirement === 'english') {
      description += `   • Maîtrise de l'Anglais (obligatoire)\n`;
    }
  }

  // Critères personnels
  description += `\n👤 CRITÈRES DU CANDIDAT :\n`;
  
  if (data.gender && data.gender !== 'any') {
    const genderLabel = data.gender === 'male' ? 'Homme' : 'Femme';
    description += `   • Genre : ${genderLabel}\n`;
  }

  if (data.maritalStatus && data.maritalStatus !== 'any') {
    const maritalLabel = data.maritalStatus === 'single' ? 'Célibataire' : 'Marié(e)';
    description += `   • Statut marital : ${maritalLabel}\n`;
  }

  if (data.minAge || data.maxAge) {
    description += `   • Âge : `;
    if (data.minAge && data.maxAge) {
      description += `entre ${data.minAge} et ${data.maxAge} ans\n`;
    } else if (data.minAge) {
      description += `${data.minAge} ans minimum\n`;
    } else if (data.maxAge) {
      description += `${data.maxAge} ans maximum\n`;
    }
  }

  if (data.childrenAccepted === false) {
    description += `   • Sans enfants à charge\n`;
  }

  if (data.drivingLicense && data.drivingLicense !== 'not_required') {
    const licenseLabel = data.drivingLicense === 'required' ? 'Obligatoire' : 'Souhaité (un plus)';
    description += `   • Permis de conduire : ${licenseLabel}\n`;
  }

  // Informations du poste
  description += '\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
  description += '\n📍 INFORMATIONS DU POSTE\n';
  description += '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n';

  description += `📌 Localisation : ${data.city}${data.country ? ', ' + data.country : ''}\n`;
  
  if (data.remote) {
    description += `🏠 Télétravail : Possible\n`;
  }

  if (data.contractType) {
    const contractLabels: { [key: string]: string } = {
      'full_time': 'Temps plein (CDI)',
      'part_time': 'Temps partiel',
      'contract': 'CDD',
      'internship': 'Stage',
      'freelance': 'Freelance'
    };
    description += `📝 Type de contrat : ${contractLabels[data.contractType] || data.contractType}\n`;
  }

  if (data.salaryMin || data.salaryMax) {
    description += `💰 Rémunération : `;
    if (data.salaryMin && data.salaryMax) {
      description += `${data.salaryMin.toLocaleString()} - ${data.salaryMax.toLocaleString()} ${data.currency || 'XOF'}\n`;
    } else if (data.salaryMin) {
      description += `À partir de ${data.salaryMin.toLocaleString()} ${data.currency || 'XOF'}\n`;
    } else if (data.salaryMax) {
      description += `Jusqu'à ${data.salaryMax.toLocaleString()} ${data.currency || 'XOF'}\n`;
    }
  }

  // Section contact et candidature
  description += '\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
  description += '\n📬 COMMENT POSTULER\n';
  description += '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n';

  description += '📄 DOCUMENTS À FOURNIR :\n';
  description += '   • CV détaillé\n';
  description += '   • Lettre de motivation\n';
  if (data.education && data.education.length > 0) {
    description += '   • Copies des diplômes\n';
  }
  description += '   • Certificats de travail (si disponibles)\n';

  description += '\n📧 COORDONNÉES POUR POSTULER :\n';
  
  if (data.contactEmail) {
    description += `   • Email : ${data.contactEmail}\n`;
  }
  
  if (data.contactPhone) {
    description += `   • Téléphone : ${data.contactPhone}\n`;
  }
  
  if (data.contactWhatsApp) {
    description += `   • WhatsApp : ${data.contactWhatsApp}\n`;
  }

  if (data.contactAddress) {
    description += `\n📍 Adresse :\n   ${data.contactAddress}\n`;
  }

  if (data.contactWebsite) {
    description += `   • Site web : ${data.contactWebsite}\n`;
  }

  description += '\n⚠️ Merci d\'envoyer votre dossier complet avec l\'objet : "Candidature ' + data.title + '"\n';
  description += '\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';

  return description;
};

